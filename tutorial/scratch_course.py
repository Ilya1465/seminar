"""Модуль 1 — программирование на Scratch для самых маленьких.

Контент тем и уроков: теория с цветными блоками Scratch (CSS-классы .sb-*)
и викторины. Карточки показывает тот же плеер, что и уроки Python.
Scratch — проект MIT: scratch.mit.edu. Названия блоков — русская локализация Scratch.
"""


def B(cat, text):
    """Блок Scratch: <span class="sb sb-motion">двигаться на 10 шагов</span>."""
    return '<span class="sb sb-%s">%s</span>' % (cat, text)


def T(title, *paras):
    """Карточка теории."""
    return {'type': 'theory', 'title': title, 'html': ''.join('<p>%s</p>' % p for p in paras)}


def Q(question, correct, wrong1, wrong2, explain):
    """Викторина с одним правильным и двумя неправильными вариантами."""
    return {
        'type': 'quiz',
        'title': 'Проверим понимание',
        'question': question,
        'options': [
            {'text': wrong1, 'correct': False},
            {'text': correct, 'correct': True},
            {'text': wrong2, 'correct': False},
        ],
        'explain': explain,
    }


def LV(level_id, title, intro, grid, start, goal, direction=1,
       blocks=('forward', 'left', 'right', 'repeat'), hero='🐱'):
    """Игровая карточка: герой должен доехать до звезды.
    grid: '.' свободно, '#' дерево, 'G' звезда. direction: 0 вверх, 1 вправо,
    2 вниз, 3 влево."""
    return {
        'type': 'blocks',
        'title': title,
        'intro': intro,
        'level': {
            'id': level_id,
            'grid': grid,
            'start': start,
            'goal': goal,
            'dir': direction,
            'blocks': list(blocks),
            'hero': hero,
        },
    }


def topic(slug, title, description, lessons):
    return {
        'slug': slug,
        'title': title,
        'description': description,
        'module': 1,
        'lessons': [{'title': lesson_title, 'theory_html': '', 'problems': [], 'cards': cards}
                    for lesson_title, cards in lessons],
    }


